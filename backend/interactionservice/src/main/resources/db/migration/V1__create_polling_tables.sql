
CREATE TABLE polls (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL,
    question VARCHAR(500) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_poll_status
        CHECK (status IN ('DRAFT', 'LIVE', 'CLOSED'))
);

CREATE TABLE poll_options (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    poll_id BIGINT NOT NULL,
    option_text VARCHAR(200) NOT NULL,

    CONSTRAINT fk_poll_option
        FOREIGN KEY (poll_id)
        REFERENCES polls(id)
        ON DELETE CASCADE
);

CREATE TABLE votes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    poll_id BIGINT NOT NULL,
    option_id BIGINT NOT NULL,
    participant_id UUID NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_vote_poll
        FOREIGN KEY (poll_id)
        REFERENCES polls(id),

    CONSTRAINT fk_vote_option
        FOREIGN KEY (option_id)
        REFERENCES poll_options(id),

    CONSTRAINT uq_poll_participant
        UNIQUE (poll_id, participant_id)
);

CREATE INDEX idx_polls_event_id
    ON polls(event_id);

CREATE INDEX idx_poll_options_poll_id
    ON poll_options(poll_id);

CREATE INDEX idx_votes_poll_option
    ON votes(poll_id, option_id);
